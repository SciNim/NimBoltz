  let apop = [exp(g.ei[1] / inp.kT), exp(g.ei[3] / inp.kT), exp(g.ei[5] / inp.kT)]
  let bethe = bornBethe(6.085, 69.20)
  let fragments = [
    (curve(xion1, yion1), 0.3513'f32), (curve(xion2, yion2), 0.2568),
    (curve(xion3, yion3), 0.2153), (curve(xion4, yion4), 0.0289),
    (curve(xion5, yion5), 0.0088), (curve(xion6, yion6), 0.0022),
    (curve(xion7, yion7), 0.0416), (curve(xion8, yion8), 0.0141),
    (curve(xion9, yion9), 0.0110), (curve(xion10, yion10), 0.0042),
    (curve(xion11, yion11), 0.0659), (curve(xion12, yion12), 0.0032)]
  # dipole active vibrations: (level of the superelastic collision, Born
  # amplitude, table, resonance amplitude)
  let dipoleModes = [(1, 0.2127'f32, curve(xvibv7, yvibv7), 0.658'f32),
                     (3, 0.0163, curve(xvibv3, yvibv3), 1.400),
                     (5, 0.0194, curve(xvibv2, yvibv2), 2.128)]
  let v1 = curve(xvibv1, yvibv1)
  # levels that are the 1.85 eV resonance alone, with its amplitude
  let resonances = [(7, 0.336'f32), (9, 0.490), (10, 0.238), (12, 0.126)]
  # triplets: (level, table, amplitude, forward scattering above)
  let triplets = [(13, curve(x3bp1, y3bp1), 1.32'f32, 50.0),
                  (14, curve(x3bp2, y3bp2), 1.32, 50.0)]
  let tripletsLin = [(17, curve(xexc1, yexc1), 1.65'f32),
                     (31, curve(xexc2, yexc2), 1.02)]
  var strengths: array[15 .. 52, float32]
  for j, f in [0.017732'f32, 0.015213, 0.0, 0.034244, 0.019948, 0.034130,
               0.023435, 0.031670, 0.027491, 0.028084, 0.022596, 0.020682,
               0.036543, 0.067959, 0.026841, 0.036796, 0.0, 0.036494, 0.059042,
               0.053004, 0.067965, 0.102085, 0.061741, 0.027011, 0.092934,
               0.194800, 0.118570, 0.065180, 0.054383, 0.009276, 0.010884,
               0.040982, 0.044933, 0.034056, 0.038851, 0.025192, 0.015084,
               0.002400]:
    strengths[15 + j] = f
  let ioffion = inp.offsets(g.eion[1 .. g.nion])
  let ioffn = inp.offsets(g.ei[1 .. g.nin], magnitude = true)

  for i, en in inp.bins:
    let r = relativistic(en)
    let qel = logLog(xen, yel, en) * 1e-16
    let qmt = logLog(xen, ymt, en) * 1e-16
    let pq2 = 1.0 - logLog(xen, yeps, en)
    let pq1 = 0.5 + (qel - qmt) / qel
    g.peqel[2, i] = case inp.naniso
                    of 0: 0.0
                    of 1: pq1
                    else: pq2
    g.q[2, i] = if inp.naniso == 0: qmt else: qel

    # breakup channels: tables, then fractions of the counting ionisation
    # (Born-Bethe above its table); the K shell is taken out of them
    for k in 1 .. g.nion:
      g.qion[k, i] = 0.0
      g.peqion[k, i] = 0.0
    for k in 1 .. 12:
      if en <= g.eion[k]: continue
      let (c, fraction) = fragments[k - 1]
      g.qion[k, i] =
        if en <= c.x[^1]: lin(c, en) * 1e-16
        elif en > xionc[^1]: bethe.ionisation(r) * fraction
        else: logLog(xionc, yionc, en) * 1e-16 * fraction
    if en > g.eion[13]:
      g.qion[13, i] = 2.0 * lin(xion13, yion13, en) * 1e-16
      var qsum = 0.0
      for k in 1 .. 12: qsum = qsum + g.qion[k, i]
      if qsum != 0.0:
        let fac = (qsum - g.qion[13, i]) / qsum
        for k in 1 .. 12: g.qion[k, i] = g.qion[k, i] * fac
    for k in 1 .. g.nion:
      if en > 2.0 * g.eion[k]:
        g.peqion[k, i] = if inp.naniso == 0: 0.0 else: g.peqel[2, i - ioffion[k - 1]]

    g.q[4, i] = 0.0
    if en >= xatt[0] and en <= xatt[^1]: g.q[4, i] = lin(xatt, yatt, en) * 1e-16
    g.qatt[1, i] = g.q[4, i]
    g.q[5, i] = 0.0
    g.q[6, i] = 0.0

    for j in 1 .. g.nin:
      g.qin[j, i] = 0.0
      g.peqin[j, i] = 0.0
    # V7, V3, V2: Born dipole, table and resonance; detailed balance for
    # the superelastic ones
    for m, (j, amp, c, ares) in dipoleModes:
      let e2 = en + g.ei[j + 1]
      var q = vibrationalDipole(amp, g.ei[j], en)
      if e2 > c.x[^1]: q = q + c.y[^1] * pow2(c.x[^1] / e2)
      else:
        q = q + e2 * lin(c, e2) / en
        if e2 > xres[0] and e2 < xres[^1]: q = q + e2 * lin(xres, yres, e2) / en * ares
      g.qin[j, i] = q * apop[m] / (1.0 + apop[m]) * 1e-16
      if en > g.ei[j + 1]:
        q = vibrationalDipole(amp, g.ei[j + 1], en)
        if en > c.x[^1]: q = q + c.y[^1] * pow2(c.x[^1] / en)
        else:
          q = q + lin(c, en)
          if en > xres[0] and en < xres[^1]: q = q + lin(xres, yres, en) * ares
        g.qin[j + 1, i] = q * 1e-16
    if en > g.ei[8]:
      var q = vibrationalDipole(0.0084'f32, g.ei[8], en)
      if en > v1.x[^1]: q = q + v1.y[^1] * pow2(v1.x[^1] / en)
      else:
        q = q + lin(v1, en)
        if en > xres[0] and en < xres[^1]: q = q + lin(xres, yres, en) * 1.050'f32
      g.qin[8, i] = q * 1e-16
    for (j, amp) in resonances:
      if en > g.ei[j] and en > xres[0] and en < xres[^1]:
        g.qin[j, i] = logLog(xres, yres, en) * 1e-16 * amp
    if en > g.ei[11]:
      g.qin[11, i] = (if en > xvib2v1[^1]: float64(yvib2v1[^1]) * pow2(xvib2v1[^1] / en)
                      else: lin(xvib2v1, yvib2v1, en)) * 1e-16
    # (the resonance-only levels never get there: above 20 eV they are
    # outside the resonance table)
    if en > 20.0:
      for j in [1, 2, 3, 4, 5, 6, 8, 11]: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]

    for (j, c, amp, fwd) in triplets:
      if en <= g.ei[j]: continue
      g.qin[j, i] = if en > c.x[^1]: c.y[^1] * pow2(c.x[^1] / en) * 1e-16 * amp
                    else: logLog(c.x, c.y, en) * 1e-16 * amp
      if inp.naniso != 0 and en > fwd: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
    for (j, c, amp) in tripletsLin:
      if en <= g.ei[j]: continue
      g.qin[j, i] = if en > c.x[^1]: c.y[^1] * pow2(c.x[^1] / en) * 1e-16 * amp
                    else: lin(c, en) * 1e-16 * amp
      if inp.naniso != 0 and en > 100.0: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
    for j in 15 .. 52:
      let f = strengths[j]
      if f == 0.0 or en <= g.ei[j]: continue
      g.qin[j, i] = nonNegative(dipole(f, g.ei[j], r, en) / (en + g.ei[j] + g.e[3]))
      if en > 3.0 * g.ei[j]: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
    # tabulated angular distribution of the dipole levels near threshold
    for j in 15 .. 52:
      if j == 17 or j == 31: continue
      let epoint = en / g.ei[j]
      if epoint >= 1.0 and epoint <= 20.0:
        g.peqin[j, i] = 1.0 - lin(enrot, yepsr, epoint)
  g.dropLevelsAbove(inp.efinal)
  if g.nin <= 12: g.nin = 12
