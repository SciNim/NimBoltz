    if en <= xel[0]:
      qela = yel[0] * 1e-16
      qmmt = ymt[0] * 1e-16
      eps = yeps[0]
    else:
      qela = logLog(xel, yel, en) * 1e-16
      qmmt = logLog(xel, ymt, en) * 1e-16
      eps = lin(xel, yeps, en)
    eps = 1.0 - eps
    g.q[2, i] = qela * anorm
    g.peqel[2, i] = eps

    for k in 1 .. g.nion:
      g.peqion[k, i] = 0.0
      g.qion[k, i] = 0.0
    block ionisation:
      var qcount: float64
      if en > 1000.0: qcount = bethe.ionisation(r)
      elif en <= g.eion[1]: break ionisation
      else: qcount = logLog(xionc, yionc, en) * 1e-16
      for k, c in ions:
        if en > c.x[^1]: g.qion[k + 1, i] = qcount * shares[k]
        elif en <= c.x[0]: break ionisation
        else: g.qion[k + 1, i] = logLog(c, en) * 1e-16
      for k, (c, unit) in kShells:
        if en <= c.x[0]: break ionisation
        g.qion[k + 28, i] = logLog(c, en) * unit
    for k in 1 .. g.nion:
      if en > 2.0 * g.eion[k]: g.peqion[k, i] = g.peqel[2, i - ioffion[k - 1]]

    for k, c in attach:
      g.qatt[k + 1, i] = 0.0
      if en > c.x[0] and en < c.x[^1]: g.qatt[k + 1, i] = lin(c, en) * 1e-20 * ampatt
    g.q[4, i] = 0.0
    g.q[5, i] = 0.0
    g.q[6, i] = 0.0

    for l in 1 .. g.nin:
      g.qin[l, i] = 0.0
      g.peqin[l, i] = 0.0
    if en <= 1000.0:
      # dipole rotations: Born cross sections with tabulated angular
      # distributions (EN / |EIN| stays inside the tables)
      let enrt = sqrt(en)
      for l in 1 .. 26:
        let al = float64(l)
        let s = sqrt(en - g.ei[l])
        g.qin[l, i] = pj[l] * dbk * ln((enrt + s) / (s - enrt)) * al / ((2.0 * al + 1.0) * en) * amprot
      block excitations:
        if en <= g.ei[27]: break excitations
        let s = sqrt(en - g.ei[27])
        g.qin[27, i] = frot0 * dbk * ln((enrt + s) / (enrt - s)) / en * amprot
        for l in 28 .. 52:
          if en <= g.ei[l]: break excitations
          let al = float64(l - 27)
          let s = sqrt(en - g.ei[l])
          g.qin[l, i] = pj[l - 27] * dbk * ln((enrt + s) / (enrt - s)) * (al + 1.0) /
                        ((2.0 * al + 1.0) * en) * amprot
      for l in 1 .. 26:
        g.peqin[l, i] = 1.0 - lin(enrts, yepsr, en / abs(g.ei[l]))
      for l in 27 .. 52:
        g.peqin[l, i] = if en <= g.ei[l]: 0.0
                        else: 1.0 - lin(enrot, yepsr, en / abs(g.ei[l]))

    # vibrations: V1 superelastic (53) and inelastic (54), V2, V3; Born
    # dipole plus resonance
    if en > 0.0:
      let efac = sqrt(1.0 - g.ei[53] / en)
      g.qin[53, i] = ampv1 * ln((efac + 1.0) / (efac - 1.0)) / en
      let e2 = en + g.ei[54]
      let ares = if e2 <= xvibh[0] or e2 >= xvibh[^1]: 0.0
                 else: ampv1r * e2 * lin(xvibh, yvibh, e2) / en
      g.qin[53, i] = g.qin[53, i] + ares
      g.qin[53, i] = g.qin[53, i] * apop2 / (1.0 + apop2) * 1e-16
      if en >= 4.0: g.peqin[53, i] = g.peqel[2, i - ioffn[52]]
    if en > g.ei[54]:
      let efac = sqrt(1.0 - g.ei[54] / en)
      g.qin[54, i] = ampv1 * ln((1.0 + efac) / (1.0 - efac)) / en
      let ares = if en <= xvibh[0] or en >= xvibh[^1]: 0.0
                 else: ampv1r * lin(xvibh, yvibh, en)
      g.qin[54, i] = g.qin[54, i] + ares
      g.qin[54, i] = g.qin[54, i] / (1.0 + apop2) * 1e-16
      if en >= 4.0: g.peqin[54, i] = g.peqel[2, i - ioffn[53]]
    for (j, amp, ampr) in [(55, ampv2, ampv2r), (56, ampv3, ampv3r)]:
      if en <= g.ei[j]: continue
      let efac = sqrt(1.0 - g.ei[j] / en)
      g.qin[j, i] = amp * ln((1.0 + efac) / (1.0 - efac)) / en
      let ares = if en <= xvibh[0] or en >= xvibh[^1]: 0.0
                 else: ampr * lin(xvibh, yvibh, en)
      g.qin[j, i] = (g.qin[j, i] + ares) * 1e-16
      if en >= 4.0: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]

    for (j, c, amp) in triplets:
      if en <= g.ei[j]: continue
      g.qin[j, i] = if en > c.x[^1]: c.y[^1] * pow2(c.x[^1] / en) * 1e-16 * amp
                    else: logLog(c, en) * 1e-16 * amp
      if en > 2.0 * g.ei[j]: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
    for (j, f) in dipoles:
      if en <= g.ei[j]: continue
      g.qin[j, i] = nonNegative(dipole(f, g.ei[j], r, en, bbm) / (en + g.ei[j] + g.e[3]))
      let epoint = en / abs(g.ei[j])
      g.peqin[j, i] = if epoint > 500.0: g.peqel[2, i - ioffn[j - 1]]
                      else: 1.0 - lin(enrot, yepsr, epoint)

    # (no total: the sums are commented out in Magboltz, Q(1) is not set)
  g.dropLevelsAbove(inp.efinal, first = 54)
