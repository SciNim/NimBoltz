proc phaseShifts(en: float64): tuple[qela, qmom: float64] =
  ## elastic and momentum transfer cross sections below 1 eV from the
  ## modified effective range theory (phase shifts in the small angle form)
  const lmax = 100
  let apol = float64(2.672'f32)               # polarisability (a₀³)
  let (aa, dd, ff) = (float64(0.2135'f32), float64(3.86'f32), float64(-2.656'f32))
  let (a1, b1, a2) = (float64(1.846'f32), float64(3.29'f32), float64(-0.037'f32))
  let api = arccos(-1.0)
  let ak = sqrt(en / ary)
  let ak2 = ak * ak
  let ak3 = ak2 * ak
  let ak4 = ak3 * ak
  let ak5 = ak4 * ak
  let an0 = -(aa * ak * (1.0 + 4.0 * apol / 3.0 * ak2 * ln(ak))) -
            api * apol / 3.0 * ak2 + dd * ak3 + ff * ak4
  let an1 = (api / 15.0 * apol * ak2 - a1 * ak3) / (1.0 + b1 * ak2)
  let an2 = api * apol * ak2 / 105.0 - a2 * ak5
  var anhigh = an2
  var sum = pow2(sin(an0 - an1)) + 2.0 * pow2(sin(an1 - an2))
  var sigel = pow2(sin(an0)) + 3.0 * pow2(sin(an1))
  for j in 2 .. lmax - 1:
    # (single precision, as written)
    let l = float32(j)
    let anlow = anhigh
    let d = (2.0'f32 * l + 5.0'f32) * (2.0'f32 * l + 3.0'f32) * (2.0'f32 * l + 1.0'f32)
    anhigh = api * apol * ak2 / float64(d)
    let sumi = float64(6.0'f32 / (d * (2.0'f32 * l - 1.0'f32)))
    sum = sum + float64(l + 1.0'f32) * pow2(sin(api * apol * ak2 * sumi))
    sigel = sigel + float64(2.0'f32 * l + 1.0'f32) * pow2(sin(anlow))
  (sigel * 4.0 * pir2 / ak2, sum * 4.0 * pir2 / ak2)

