    # charge states 1..3: tables, then Born-Bethe; K shell: table
    for k in 1 .. 4:
      g.qion[k, i] = 0.0
      g.peqion[k, i] = iso
      let eion = g.eion[k]
      if en <= eion: continue
      if k == 4:
        g.qion[4, i] = lin(xksh, yksh, en) * 1e-16
        g.peqion[4, i] = g.peqel[2, i - ioffion[3]]
        continue
      g.qion[k, i] =
        case k
        of 1: (if en > xion[^1]: bethe.ionisation(r, 0.9594) else: lin(xion, yin1, en) * 1.0e-16)
        of 2: (if en > xin2[^1]: bethe.ionisation(r, 0.0388) else: lin(xin2, yin2, en) * 1.0e-16)
        else: (if en > xin3[^1]: bethe.ionisation(r, 0.00215) else: lin(xin3, yin3, en) * 1.0e-16)
      if en > 2.0 * eion:
        g.peqion[k, i] = g.peqel[2, i - ioffion[k - 1]]
    # counting ionisation: the charge states make up what the K shell leaves
    let qcount =
      if en <= g.e[3]: 0.0
      elif en > xion[^1]: bethe.ionisation(r)
      else: lin(xion, yinc, en) * 1.0e-16
    let qcorr = if qcount == 0.0: 1.0 else: (qcount - g.qion[4, i]) / qcount
    for k in 1 .. 3: g.qion[k, i] = g.qion[k, i] * qcorr

    for j, x in excitations:
      let ein = g.ei[j + 1]
      g.peqin[j + 1, i] = iso
      if en <= ein:
        g.qin[j + 1, i] = 0.0
        continue
      g.qin[j + 1, i] = x.excitation(ein, g.e[3], r, en, absNegative, ionFirst = false)
      if en > 2.0 * ein:
        g.peqin[j + 1, i] = g.peqel[2, i - ioffn[j]]
  g.dropLevelsAbove(inp.efinal)
