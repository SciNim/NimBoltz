    (24.50708, " EXC  N1P SUM HI RESONANT          ELOSS= 24.50708"),
  ])
  g.penning(inp, 1 .. g.nin, 1.0, 1.0, 1.0, penningFormat)

  # n = 2..4 levels: tables, 1/E^n or Born-Bethe (f) above them
  let own = [
    tab(x23s, y23s, 3), tab(x21s, y21s, 1), tab(x23p, y23p, 3),
    tab(x21p, y21p, f = 0.27608), tab(x33s, y33s, 3), tab(x31s, y31s, 1),
    tab(x33p, y33p, 1), tab(x33d, y33d, 1), tab(x31d, y31d, 1),
    tab(x31p, y31p, f = 0.07342), tab(x43s, y43s, 3), tab(x41s, y41s, 1),
    tab(x43p, y43p, 3), tab(x43d, y43d, 3), tab(x41d, y41d, 1),
    tab(x43f, y43f, 4), tab(x41f, y41f, 1),
    tab(x41p, y41p, f = 0.02986)]
  # higher levels: an n = 4 level (11..18) at energies scaled by the ratio
  # of the excitation energies, times a factor; 1P levels with their
  # oscillator strengths
  var higher: seq[(int, float32, float32)]   # (level, factor, f)
  for (factor, n) in [(0.512'f32, 7), (0.296, 5), (0.187, 5), (0.553, 5)]:
    for k in 11 ..< 11 + n: higher.add (k, factor, 0.0'f32)
    if n == 7: higher.add (18, 0.0'f32, 0.01504'f32)
    elif factor == 0.296'f32: higher.add (18, 0.0'f32, 0.00863'f32)
    elif factor == 0.187'f32: higher.add (18, 0.0'f32, 0.00540'f32)
  for f in [0.00362'f32, 0.00253, 0.00184, 0.00138, 0.00106, 0.00440]:
    higher.add (18, 0.0'f32, f)
  let bethe = bornBethe(0.489, 5.50)
  let ioffion = inp.offsets(g.eion[1 .. g.nion])
  let ioffn = inp.offsets(g.ei[1 .. g.nin])
  let iso = if inp.naniso == 2: 0.0 else: 0.5

  for i, en in inp.bins:
    let r = relativistic(en)
    let qela = lin(xen, yel, en) * 1.0e-16
    let qmom = lin(xen, yem, en) * 1.0e-16
    g.elastic(inp, i, qela, qmom, pq2 = 1.0 - lin(xen, yeps, en))

    # gross and counting ionisation give the charge states 1 and 2
    var gross, counting = 0.0
    g.peqion[1, i] = iso
    g.peqion[2, i] = iso
    if en > g.eion[1]:
      if en > xion[^1]:
        gross = bethe.ionisation(r) / 0.995'f32
        counting = bethe.ionisation(r)
      else:
        gross = lin(xion, yion, en) * 1e-16
        counting = lin(xion, yinc, en) * 1.0e-16
      if en > 2.0 * g.eion[1]: g.peqion[1, i] = g.peqel[2, i - ioffion[0]]
      if en > 2.0 * g.eion[2]: g.peqion[2, i] = g.peqel[2, i - ioffion[1]]
    g.qion[1, i] = 2.0 * counting - gross
    g.qion[2, i] = nonNegative(gross - counting)

    for j in 1 .. g.nin:
      let ein = g.ei[j]
      g.qin[j, i] = 0.0
      g.peqin[j, i] = iso
      if en <= ein: continue
      g.qin[j, i] =
        if j <= 18:
          own[j - 1].excitation(ein, g.e[3], r, en, keepNegative, ionFirst = false)
        else:
          let (k, factor, f) = higher[j - 19]
          let c = own[k - 1]
          let enp = en / (ein / g.ei[k])
          if enp > c.x[^1]:
            if f == 0.0:
              factor * c.y[^1] * power(c.x[^1] / enp, c.falloff) * 1e-18
            else: dipole(f, ein, r, en) / (en + ein + g.e[3])
          else:
            # (the ratio of the oscillator strengths in single precision)
            let factor = if f == 0.0: factor else: f / c.f
            factor * lin(c.x, c.y, enp) * 1e-18
      if en > 2.0 * ein:
        g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
  g.dropLevelsAbove(inp.efinal)

proc helium4*(inp: GasInput, g: var GasXsec) = helium(inp, g, he3 = false)
