    g.qin[57, i] = (g.qin[57, i] + ares) * apop3 * 1e-16
    if en >= 2.0: g.peqin[57, i] = g.peqel[2, i - ioffn[56]]
    if en >= g.ei[58]:
      efac = sqrt(1.0 - g.ei[58] / en)
      g.qin[58, i] = avib3 * ln((1.0 + efac) / (1.0 - efac)) / en
      ares = if en <= xvibh[0] or en >= xvibh[^1]: 0.0 else: ampv3r * lin(xvibh, yvibh, en)
      g.qin[58, i] = (g.qin[58, i] + ares) * apopgs * 1e-16
      if en >= 2.0: g.peqin[58, i] = g.peqel[2, i - ioffn[57]]
    if en > g.ei[59]:
      efac = sqrt(1.0 - g.ei[59] / en)
      g.qin[59, i] = avib4 * ln((1.0 + efac) / (1.0 - efac)) / en
      ares = if en <= xvibh[0] or en >= xvibh[^1]: 0.0 else: ampv4r * lin(xvibh, yvibh, en)
      g.qin[59, i] = (g.qin[59, i] + ares) * 1e-16
      if en >= 2.0: g.peqin[59, i] = g.peqel[2, i - ioffn[58]]
    if en > g.ei[60] and en > xvibh[0] and en < xvibh[^1]:
      g.qin[60, i] = ampv5r * lin(xvibh, yvibh, en) * 1e-16
      if en >= 2.0: g.peqin[60, i] = g.peqel[2, i - ioffn[59]]

    for (j, c) in triplets:
      if en <= g.ei[j]: continue
      g.qin[j, i] = if en > c.x[^1]: c.y[^1] * pow2(c.x[^1] / en) * 1e-16
                    else: logLog(c, en) * 1e-16
      if en > 2.0 * g.ei[j]: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
    for (j, f) in dipoles:
      if en <= g.ei[j]: continue
      g.qin[j, i] = nonNegative(dipole(f, g.ei[j], r, en, bbdme) / (en + g.ei[j] + g.e[3]))
      let epoint = en / abs(g.ei[j])
      g.peqin[j, i] = if epoint > 500.0: g.peqel[2, i - ioffn[j - 1]]
                      else: 1.0 - lin(enrot, yepsr, epoint)

    var sumr, sumsupr, sumvib, sumion = 0.0
    for k in 1 .. 26: sumsupr = sumsupr + g.qin[k, i]
    for k in 27 .. 52: sumr = sumr + g.qin[k, i]
    for k in 53 .. 60: sumvib = sumvib + g.qin[k, i]
    let sumatt = 0.0 + g.qatt[1, i]
    for k in 1 .. g.nion: sumion = sumion + g.qion[k, i]
    # (the excitations 61..110 are not in the total in Magboltz)
    g.q[1, i] = g.q[2, i] + (sumr + sumsupr + sumvib + sumatt + sumion)
  g.dropLevelsAbove(inp.efinal, first = 54)
