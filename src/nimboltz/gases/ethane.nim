        else: logLog(xion, yionc, en) * 1e-16 * fraction
      if en >= 2.0 * g.eion[k]: g.peqion[k, i] = g.peqel[2, i - ioffion[k - 1]]
    if en > g.eion[16]:
      g.qion[16, i] = 2.0 * lin(xion16, yion16, en) * 1e-16
      if en >= 2.0 * g.eion[16]: g.peqion[16, i] = g.peqel[2, i - ioffion[15]]
      var qsum = 0.0
      for k in 1 .. 15: qsum = qsum + g.qion[k, i]
      if qsum != 0.0:
        let fac = (qsum - g.qion[16, i]) / qsum
        for k in 1 .. 15: g.qion[k, i] = g.qion[k, i] * fac

    g.qatt[1, i] = 0.0
    if en >= xatt1[0] and en < xatt1[^1]: g.qatt[1, i] = lin(xatt1, yatt1, en) * 1e-16
    g.qatt[2, i] = 0.0
    if en >= xatt2[0] and en < xatt2[^1]: g.qatt[2, i] = lin(xatt2, yatt2, en) * 1e-16

    for j in 1 .. g.nin:
      g.qin[j, i] = 0.0
      g.peqin[j, i] = 0.0
    # torsion (dipole) and vibrations: (de-)excitation weighted by the
    # populations, detailed balance for the superelastic ones
    g.qin[1, i] = vibrationalDipole(0.0045'f32, g.ei[1], en) * apop[0] / (1.0 + apop[0]) * 1e-16
    if en > g.ei[2]:
      g.qin[2, i] = vibrationalDipole(0.0045'f32, g.ei[2], en) * 1.0 / (1.0 + apop[0]) * 1e-16
    for m in 1 .. 3:
      let c = modes[m - 1]
      let ein = g.ei[2 * m + 2]
      let e2 = en + ein
      let qs = if e2 > c.x[^1]: c.y[^1] * pow2(c.x[^1] / e2) else: e2 * lin(c, e2) / en
      g.qin[2 * m + 1, i] = qs * apop[m] / (1.0 + apop[m]) * 1e-16
      if en > ein:
        g.qin[2 * m + 2, i] = lin(c.x, c.y, en, falloff = 2) / (1.0 + apop[m]) * 1e-16
    if en > g.ei[9]: g.qin[9, i] = lin(xvib4, yvib4, en, falloff = 2) * 1e-16
    if en > g.ei[10]: g.qin[10, i] = lin(xvib5, yvib5, en, falloff = 2) * 1e-16
    if en > 10.0:
      for j in 1 .. 10: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]

    for j in 11 .. 55:
      let ein = g.ei[j]
      if en <= ein: continue
      let x = dissociation[j]
      g.qin[j, i] =
        if x.f == 0.0: lin(x.x, x.y, en, x.falloff) * x.unit
        else: nonNegative(dipole(x.f, ein, r, en) / (en + ein + g.e[3]))
      if en > (if j <= 34: 3.0 else: 2.0) * ein:
        g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
  g.dropLevelsAbove(inp.efinal)
