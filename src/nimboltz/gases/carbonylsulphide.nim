proc carbonylSulphide*(inp: GasInput, g: var GasXsec) =
  g.describe(inp, " COS  -2001---", " COS  -2001---", mass = 60.0761)
  for k in 1 .. 6: g.kel[k] = 0
  g.scrp[2] = " ELASTIC       COS"
  g.e[3] = 11.19'f32
  g.shells [(0.0'f32, 11.19'f32, 0, 0.0'f32, " IONISATION    ELOSS= 11.19")]
  g.attachment [" ATTACHMENT"]
  g.levels(inp, [
    (-0.064'f32, " VIB V2        ELOSS= -0.064"),
    (0.064, " VIB V2        ELOSS=  0.064"),
    (-0.107, " VIB V1        ELOSS= -0.107"),
    (0.107, " VIB V1        ELOSS=  0.107"),
    (-0.128, " VIB 2V2       ELOSS= -0.128"),
    (0.128, " VIB 2V2       ELOSS=  0.128"),
    (0.256, " VIB V3        ELOSS=  0.256"),
    (0.380, " VIB NV1       ELOSS=  0.380"),
    (0.512, " VIB           ELOSS=  0.512"),
    (7.00, " EXC           ELOSS=  7.00")])
  for j in 1 .. g.nin: g.kin[j] = 0

  let vib = [curve(xvib1, yvib1), curve(xvib2, yvib2), curve(xvib3, yvib3)]
  let apop = [exp(g.ei[1] / inp.kT), exp(g.ei[3] / inp.kT),
              exp(g.ei[5] / inp.kT)]
  let levels = [(8, curve(xvib5, yvib5)), (9, curve(xvib6, yvib6)),
                (10, curve(xexc, yexc))]
  for i, en in inp.steps:
    g.q[2, i] = if en == 0.0: 1900e-16 else: logLog(xen, yxsec, en) * 1e-16
    g.q[3, i] = if en < g.e[3]: 0.0 else: lin(xion, yion, en) * 1e-16
    g.q[4, i] = 0.0
    if en >= float64(xatt[0]) and en <= float64(xatt[^1]):
      g.q[4, i] = lin(xatt, yatt, en) * 1e-16
    g.qatt[1, i] = g.q[4, i]
    g.q[5, i] = 0.0
    g.q[6, i] = 0.0
    # V2, V1, 2V2: de-excitation (detailed balance on the excitation's
    # table) and excitation, weighted by the populations
    for k in 0 .. 2:
      let (jd, je) = (2 * k + 1, 2 * k + 2)
      g.qin[jd, i] = 0.0
      if en != 0.0:
        let eup = en + g.ei[je]
        g.qin[jd, i] = eup * lin(vib[k], eup) / en
        g.qin[jd, i] = g.qin[jd, i] * apop[k] / (1.0 + apop[k]) * 1e-16
      g.qin[je, i] = 0.0
      if en > g.ei[je]:
        g.qin[je, i] = lin(vib[k], en)
        g.qin[je, i] = g.qin[je, i] / (1.0 + apop[k]) * 1e-16
    g.qin[7, i] = 0.0
    if en > g.ei[7]:
      g.qin[7, i] = vibrationalDipole(float64(0.639'f32), g.ei[7], en)
      g.qin[7, i] = (g.qin[7, i] + lin(xvib4, yvib4, en)) * 1e-16
    for (j, c) in levels:
      g.qin[j, i] = 0.0
      if en > g.ei[j]: g.qin[j, i] = lin(c, en) * 1e-16
    var q = g.q[2, i] + g.q[3, i] + g.q[4, i]
    for j in 1 .. 10: q = q + g.qin[j, i]
    g.q[1, i] = q
  g.dropLevelsAbove(inp.efinal, first = 7)
