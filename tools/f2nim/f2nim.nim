## f2nim: translates magboltz-*.f into Nim modules, one per program unit.
##
## Usage: f2nim <source.f> <outdir> [UNIT ...]
##   Translates all units (or only the listed ones; COMMON blocks always).
##   DRAND48 and RM48 are skipped: they are hand-ported in port/rm48.nim.

import std/[os, tables, sets, strutils, strformat, algorithm, sequtils]
import fast, fparse, fsema, fgen, ftransform

const skipUnits = ["DRAND48", "RM48"]

## Irreducible control flow (loops with two entries) is made structurable by
## node splitting at these labels, see `splitLabel`.
const splitLabels = {"MONTEFD": @[18], "MONTEFDT": @[18]}.toTable

proc walk(list: seq[Stmt], f: proc(st: Stmt)) =
  for st in list:
    f(st)
    case st.kind
    of sIf: walk(@[st.then], f)
    of sIfBlock:
      for b in st.bodies: walk(b, f)
    of sDo: walk(st.body, f)
    else: discard

proc resolveUnit(g: Gen, ui: UnitInfo) =
  g.ui = ui
  proc ioRes(g: Gen, items: seq[IoItem]) =
    for it in items:
      if it.kind == ioExpr: g.resolve(it.e)
      else:
        discard ui.getOrImplicit(it.doVar)
        g.resolve(it.lo)
        g.resolve(it.hi)
        if it.step != nil: g.resolve(it.step)
        g.ioRes(it.items)
  walk(ui.u.body) do (st: Stmt):
    case st.kind
    of sAssign:
      g.resolve(st.lhs)
      g.resolve(st.rhs)
    of sIf: g.resolve(st.cond)
    of sIfBlock:
      for c in st.conds: g.resolve(c)
    of sDo:
      discard ui.getOrImplicit(st.dvar)
      g.resolve(st.dlo)
      g.resolve(st.dhi)
      if st.dstep != nil: g.resolve(st.dstep)
    of sCGoto: g.resolve(st.sel)
    of sCall:
      for a in st.cargs: g.resolve(a)
      ui.callees.incl st.callee
    of sWrite: g.ioRes(st.witems)
    of sRead: g.ioRes(st.ritems)
    of sFormat: ui.formats[st.label] = st.ftext
    else: discard

proc buildCommons(prog: Program) =
  type Variant = seq[CommonMember]
  var variants: OrderedTable[string, seq[(Variant, string)]]
  for ui in prog.units.values:
    var blocks: OrderedTable[string, Variant]
    for s in ui.syms.values:
      if s.storage == stCommon:
        var v = blocks.getOrDefault(s.blk)
        if v.len <= s.idx: v.setLen(s.idx+1)
        v[s.idx] = CommonMember(name: s.name, typ: s.typ, clen: s.clen, dims: s.dims)
        blocks[s.blk] = v
    for b, v in blocks:
      variants.mgetOrPut(b, @[]).add (v, ui.u.name)
  for b, vs in variants:
    var counts: CountTable[string]
    for (v, _) in vs: counts.inc v.mapIt(it.name).join(",")
    let best = counts.largest.key
    var canon: Variant
    for (v, _) in vs:
      if v.mapIt(it.name).join(",") == best: canon = v
    for (v, un) in vs:
      if v.len != canon.len: serr(&"COMMON /{b}/ length differs in {un}")
      for i in 0 ..< v.len:
        if v[i].typ != canon[i].typ or v[i].dims != canon[i].dims or v[i].clen != canon[i].clen:
          serr(&"COMMON /{b}/ member {i+1} ({v[i].name}) differs in {un}")
    for m in canon.mitems: m.nim = nimName(m.name)
    prog.commons[b] = CommonBlock(name: b, nim: b.toLowerAscii,
      typeName: "Common" & b[0] & b[1..^1].toLowerAscii, members: canon)

proc assignNames(prog: Program) =
  var taken: HashSet[string]
  for r in reservedNames: taken.incl normId(r)
  for ui in prog.units.values: taken.incl normId(ui.procName)
  # COMMON globals must not collide with any local name either
  var localNames: HashSet[string]
  for ui in prog.units.values:
    for s in ui.syms.values: localNames.incl normId(s.name.toLowerAscii)
  for b in prog.commons.mvalues:
    if normId(b.nim) in taken or normId(b.nim) in localNames:
      b.nim = "c" & b.name[0] & b.name[1..^1].toLowerAscii
    taken.incl normId(b.nim)
  for ui in prog.units.values:
    var mine = taken
    for s in ui.syms.values:
      if s.storage in {stCommon, stResult}: continue
      var n = nimName(s.name)
      while normId(n.strip(chars = {'`'})) in mine: n = n.strip(chars = {'`'}) & "v"
      s.nim = n
      mine.incl normId(n.strip(chars = {'`'}))

proc computeIntents(g: Gen) =
  for ui in g.prog.units.values:
    ui.outParams = newSeq[bool](ui.u.params.len)
  var changed = true
  while changed:
    changed = false
    for ui in g.prog.units.values:
      g.ui = ui
      g.scanWrites(ui, ui.u.body)
      for i, p in ui.u.params:
        let s = ui.syms[p]
        if (s.written or s.typ == tkChar and false) and not ui.outParams[i]:
          ui.outParams[i] = true
          changed = true

proc emitCommons(prog: Program, dir, srcName: string) =
  var o = &"## COMMON blocks of {srcName}. Generated by f2nim, do not edit.\n\n"
  o.add "import ../frt\n\ntype\n"
  for b in prog.commons.values:
    o.add &"  {b.typeName}* = object  ## COMMON /{b.name}/\n"
    for m in b.members:
      let s = Sym(name: m.name, typ: m.typ, clen: m.clen, dims: m.dims)
      o.add &"    {m.nim}*: {nimDeclType(s)}\n"
  o.add "\nvar\n"
  for b in prog.commons.values:
    o.add &"  {b.nim}*: {b.typeName}\n"
  writeFile(dir / "commons.nim", o)

proc dataInit(g: Gen, s: Sym): string =
  let vals = s.data.mapIt(g.emitAs(it, s.typ))
  case s.dims.len
  of 0: vals[0]
  of 1:
    var o = "[\n"
    var line = "    "
    for i, v in vals:
      if line.len + v.len > 78:
        o.add line.strip(leading = false) & "\n"
        line = "    "
      line.add v & ", "
    o.add line.strip(leading = false) & "]"
    o
  of 2:
    var o = &"{nimDeclType(s)}(data: [\n"
    let n1 = s.dims[0]
    for j in 0 ..< s.dims[1]:
      o.add "    [" & vals[j*n1 ..< (j+1)*n1].join(", ") & "],\n"
    o & "  ])"
  else: serr("DATA for rank-3 array " & s.name)

proc emitUnit(g: Gen, ui: UnitInfo, dir, srcName: string) =
  g.ui = ui
  g.lines = @[]
  let u = ui.u
  # body first: emission may create implicit locals and temporaries
  g.emitList(u.body, 1)
  let body = g.lines
  var o = &"## {($u.kind)[2..^1].toUpperAscii} {u.name} of {srcName} (line {u.line}).\n"
  o.add "## Generated by f2nim, do not edit.\n\n"
  o.add "import ../frt, commons\n"
  var imps: seq[string]
  for c in ui.callees:
    if c in g.prog.units and c != u.name: imps.add g.prog.units[c].modName
  if imps.len > 0: o.add "import " & imps.sorted.deduplicate.join(", ") & "\n"
  o.add "\n"
  for c in u.headComments:
    let t = c.strip
    if t.len > 0 and not t.allCharsInSet({'-', '*', '=', 'C', '+', '.'}): o.add "# " & t & "\n"
  # constants
  var consts: seq[string]
  for s in ui.syms.values:
    if s.storage == stParam and s.pval != nil:
      consts.add &"  {s.nim} = {g.emitAs(s.pval, s.typ)}"
  for l in toSeq(ui.formats.keys).sorted:
    consts.add &"  fmt{l} = {escape(ui.formats[l])}"
  if consts.len > 0: o.add "const\n" & consts.join("\n") & "\n\n"
  # statics: DATA/SAVE and arrays gfortran moves to static storage (> 64 KiB)
  var statics: seq[Sym]
  var locals: seq[Sym]
  for s in ui.syms.values:
    if s.storage != stLocal: continue
    if s.saved or s.data.len > 0 or s.totalSize > 65536: statics.add s
    else: locals.add s
  for s in statics:
    if s.data.len > 0:
      let kw = (if s.written: "var" else: "let")
      o.add &"{kw} {s.nim}: {nimDeclType(s)} = {g.dataInit(s)}\n"
    else:
      o.add &"var {s.nim}: {nimDeclType(s)}\n"
  if statics.len > 0: o.add "\n"
  # signature
  var params: seq[string]
  for i, p in u.params:
    let s = ui.syms[p]
    let t = nimDeclType(s)
    params.add (if ui.outParams[i]: &"{s.nim}: var {t}" else: &"{s.nim}: {t}")
  var sig = &"proc {ui.procName}*({params.join(\", \")})"
  if u.kind == ukFunction:
    let r = ui.syms[u.name]
    sig.add ": " & nimType(r.typ)
  o.add sig & " =\n"
  # locals grouped by type
  var groups: OrderedTable[string, seq[string]]
  for s in locals: groups.mgetOrPut(nimDeclType(s), @[]).add s.nim
  for t, names in groups:
    var i = 0
    while i < names.len:
      o.add &"  var {names[i ..< min(i+8, names.len)].join(\", \")}: {t}\n"
      i += 8
  o.add body.join("\n") & "\n"
  writeFile(dir / ui.modName & ".nim", o)

proc main() =
  let args = commandLineParams()
  if args.len < 2:
    quit "usage: f2nim <source.f> <outdir> [UNIT ...]"
  let src = args[0]
  let dir = args[1]
  let only = args[2..^1].mapIt(it.toUpperAscii).toHashSet
  createDir(dir)
  let units = parseUnits(readStatements(src))
  let prog = Program()
  for u in units:
    if u.name in skipUnits: continue
    for x in splitLabels.getOrDefault(u.name, @[]):
      let n = splitLabel(u, x)
      stderr.writeLine &"{u.name}: split label {x} at {n} jumps"
    let nh = hoistTails(u)
    if nh > 0: stderr.writeLine &"{u.name}: hoisted {nh} block(s) entered by jumps"
    var ui = UnitInfo(u: u)
    if u.kind == ukProgram:
      ui.procName = "magboltz"
      ui.modName = "magboltz"
    else:
      ui.procName = u.name.toLowerAscii
      ui.modName = u.name.toLowerAscii
    buildSymbols(ui)
    prog.units[u.name] = ui
  let g = Gen(prog: prog)
  for ui in prog.units.values: g.resolveUnit(ui)
  g.computeIntents()
  buildCommons(prog)
  assignNames(prog)
  emitCommons(prog, dir, src.extractFilename)
  var failed = 0
  for ui in prog.units.values:
    if only.len > 0 and ui.u.name notin only: continue
    g.labelList.clear; g.labelIdx.clear; g.gotoCount.clear
    g.listGotos.clear; g.gotoMode.clear; g.listIds.clear
    g.tmpCount = 0
    try:
      var path: seq[tuple[list, idx: int]]
      g.ui = ui
      g.collectGotos(ui.u.body, path)
      g.emitUnit(ui, dir, src.extractFilename)
    except SemaError as e:
      inc failed
      stderr.writeLine "FAILED ", ui.u.name, ": ", e.msg
  for n in g.constFoldNotes.deduplicate: stderr.writeLine "const intrinsic: ", n
  if failed > 0: quit(&"{failed} units failed", 1)

main()
