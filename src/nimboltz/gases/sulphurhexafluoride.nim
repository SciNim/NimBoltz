      g.qin[j, i] = 0.0
      g.peqin[j, i] = 0.0
      if en > g.ei[j]:
        g.qin[j, i] = tail2(c, en) * 1e-16
        g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
    # dissociation: triplets and Born dipoles, each opening on its own
    for k, (j, c) in triplets:
      g.qin[j, i] = 0.0
      g.peqin[j, i] = 0.0
      if en > g.ei[j]:
