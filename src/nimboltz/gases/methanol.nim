  for j in 1 .. g.nin: g.kin[j] = 2
  # rotational constant B0 (eV), populations of the rotational states J
  let b0 = 2.5e-4
  var pj: array[1 .. 26, float64]
  for k in 1 .. 26:
    let ak = float64(k)
    pj[k] = (2.0 * ak + 1.0) * exp(-ak * (ak + 1.0) * b0 / inp.kT)
  var sum = 1.0
  for k in 1 .. 26: sum = sum + pj[k]
  let frot0 = 1.0 / sum
  for k in 1 .. 26: pj[k] = pj[k] / sum
  # dipole rotations J -> J + 1 (levels 27..52, de-excitations 1..26)
  for k in 1 .. 26:
    let aj = float64(k) - 1.0
    g.ei[k + 26] = b0 * 2.0 * (aj + 1.0)
    g.ei[k] = -g.ei[k + 26]
  let ioffion = inp.offsets(g.eion[1 .. g.nion])
  let ioffn = inp.offsets(g.ei[1 .. g.nin], magnitude = true)
  g.penning(inp, 57 .. g.nin, 0.0, 1.0, 1.0, penningFormat, all = true)

  # dipole moment DBA (e a0), RY single precision (spelled out: the
  # compiler folds float64(x'f32) unrounded); this routine's Bohr radius
  # also enters its Born-Bethe constant
  let a0m = 0.5291772083e-8
  let ry = 13.605691909790039
  let dbk = 8.377579689025879 * ry * pow2(1.690000057220459 * a0m)
  let amprot = float64(0.1'f32)
  let bbm = 16.0 * arccos(-1.0) * a0m * a0m * ry * ry / emass2
  # vibrations: Born dipole amplitudes, resonance amplitudes
  let ampv1 = float64(0.304'f32)
  let ampv2 = float64(0.3344'f32)
  let ampv3 = float64(0.6384'f32)
  let ampv1r = float64(0.5'f32)
  let ampv2r = float64(0.5'f32)
  let ampv3r = float64(0.5'f32)
  # population of the excited V1 (superelastic level 53)
  let apop2 = exp(g.ei[53] / inp.kT)
  let bethe = bornBethe(6.125, 66.54)
  # ionisation channels: tables, shares of the counting ionisation above
  # them; K-shells
  let ions = [curve(xion1, yion1), curve(xion2, yion2), curve(xion3, yion3),
    curve(xion4, yion4), curve(xion5, yion5), curve(xion6, yion6),
    curve(xion7, yion7), curve(xion8, yion8), curve(xion9, yion9),
    curve(xion10, yion10), curve(xion11, yion11), curve(xion12, yion12),
    curve(xion13, yion13), curve(xion14, yion14), curve(xion15, yion15)]
  let shares = [0.18226'f32, 0.27883, 0.02046, 0.10296, 0.01823, 0.18418,
    0.01407, 0.00269, 0.00243, 0.00141, 0.01068, 0.00556, 0.03274, 0.00069,
    0.14280]
  let kShells = [curve(xion16, yion16), curve(xion17, yion17)]
  let attach = [curve(xatt1, yatt1), curve(xatt2, yatt2), curve(xatt3, yatt3)]
  # triplets (log-log, falloff 1/E²), Born dipoles with tabulated angular
  # distributions up to 500 times the threshold
  let triplets = [
    (57, curve(xtrp1, ytrp1), float64(0.924'f32)),
    (63, curve(xtrp2, ytrp2), float64(0.88'f32)),
    (70, curve(xtrp3, ytrp3), float64(1.0'f32)),
    (76, curve(xtrp4, ytrp4), float64(0.9'f32)),
