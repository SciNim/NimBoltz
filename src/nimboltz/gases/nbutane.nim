proc nButane*(inp: GasInput, g: var GasXsec) =
  g.describe(inp, " N-BUTANE 2003", " N-BUTANE 2003", mass = 58.1234)
  for k in 1 .. 6: g.kel[k] = 0
  g.scrp[2] = " ELASTIC       N-BUTANE"
  g.e[3] = 10.67'f32
  g.shells [(0.0'f32, 10.67'f32, 0, 0.0'f32, " IONISATION    ELOSS= 10.67")]
  g.attachment [" ATTACHMENT"]
  g.levels(inp, [
    (-0.052'f32, " VIB           ELOSS= -0.052"),
    (0.052, " VIB           ELOSS=  0.052"),
    (-0.108, " VIB           ELOSS= -0.108"),
    (0.108, " VIB           ELOSS=  0.108"),
    (0.173, " VIB           ELOSS=  0.173"),
    (0.363, " VIB           ELOSS=  0.363"),
    (0.519, " VIB           ELOSS=  0.519"),
    (7.4, " EXC           ELOSS=  7.4"),
    (9.70, " EXC           ELOSS=  9.70"),
    (17.0, " EXC           ELOSS= 17.0")])
  for j in 1 .. g.nin: g.kin[j] = 0

  let vib = [curve(xvib1, yvib1), curve(xvib2, yvib2)]
  let apop = [exp(g.ei[1] / inp.kT), exp(g.ei[3] / inp.kT)]
  let levels = [(5, curve(xvib3, yvib3)), (6, curve(xvib4, yvib4)),
                (7, curve(xvib5, yvib5)), (8, curve(xexc1, yexc1)),
                (9, curve(xexc2, yexc2)), (10, curve(xexc3, yexc3))]
  for i, en in inp.steps:
    g.q[2, i] = lin(xen, yxsec, en) * 1e-16
    g.q[3, i] = if en < g.e[3]: 0.0 else: lin(xion, yion, en) * 1e-16
    g.q[4, i] = 0.0
    if en >= float64(xatt[0]) and en <= float64(xatt[^1]):
      g.q[4, i] = lin(xatt, yatt, en) * 1e-21
    g.qatt[1, i] = g.q[4, i]
    g.q[5, i] = 0.0
    g.q[6, i] = 0.0
    for k in 0 .. 1:
      let (jd, je) = (2 * k + 1, 2 * k + 2)
      g.qin[jd, i] = 0.0
      if en != 0.0:
        let eup = en + g.ei[je]
        g.qin[jd, i] = eup * lin(vib[k], eup) * 1e-16 / en
        g.qin[jd, i] = apop[k] * g.qin[jd, i] / (1.0 + apop[k])
      g.qin[je, i] = 0.0
      if en > g.ei[je]:
        g.qin[je, i] = lin(vib[k], en) * 1e-16 / (1.0 + apop[k])
    for (j, c) in levels:
      g.qin[j, i] = 0.0
      if en > g.ei[j]: g.qin[j, i] = lin(c, en) * 1e-16
    var q = g.q[2, i] + g.q[3, i] + g.q[4, i]
    for j in 1 .. 10: q = q + g.qin[j, i]
    g.q[1, i] = q
  g.dropLevelsAbove(inp.efinal, first = 4)
