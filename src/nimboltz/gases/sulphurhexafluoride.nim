proc attachmentSegment[T](x: openArray[T], en: float64): int =
  for j in 1 .. x.high:
    if en <= x[j]: return j
  x.high

proc tail2(c: Curve, en: float64): float64 {.inline.} =
  ## the table, falling off as 1/E² above it
  if en > c.x[^1]: c.y[^1] * pow2(c.x[^1] / en) else: lin(c, en)

