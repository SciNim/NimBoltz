    for (j, f, scale) in dipoles:
      g.qin[j, i] = 0.0
      g.peqin[j, i] = 0.0
      if en > g.ei[j]:
        g.qin[j, i] = dipole(f, g.ei[j], r, en) / (en + g.ei[j] + g.e[3]) *
          float64(scale)
        if g.qin[j, i] < 0.0: g.qin[j, i] = 0.0
        if en > 3.0 * g.ei[j]: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
  g.dropLevelsAbove(inp.efinal)
