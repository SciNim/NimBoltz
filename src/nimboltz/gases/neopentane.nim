proc neopentane*(inp: GasInput, g: var GasXsec) =
  g.describe(inp, "NEO-PENTANE 03", "NEO-PENTANE 03", mass = 72.1503)
  for k in 1 .. 6: g.kel[k] = 0
  g.scrp[2] = " ELASTIC       NEO-PENTANE"
  g.e[3] = 10.35'f32
  g.shells [(0.0'f32, 10.35'f32, 0, 0.0'f32, " IONISATION    ELOSS= 10.35")]
  g.attachment [" ATTACHMENT"]
  g.levels(inp, [
    (-0.052'f32, " VIB           ELOSS= -0.052"),
    (0.052, " VIB           ELOSS=  0.052"),
    (-0.108, " VIB           ELOSS= -0.108"),
    (0.108, " VIB           ELOSS=  0.108"),
    (-0.173, " VIB           ELOSS= -0.173"),
    (0.173, " VIB           ELOSS=  0.173"),
    (0.363, " VIB           ELOSS=  0.363"),
    (0.519, " VIB           ELOSS=  0.519"),
    (7.2, " EXC           ELOSS=  7.20"),
    (9.50, " EXC           ELOSS=  9.50"),
    (17.0, " EXC           ELOSS= 17.0")])
  for j in 1 .. g.nin: g.kin[j] = 0

  # (superelastic level, its table, population of the excited state)
  let vibrations = [(1, curve(xvib1, yvib1), exp(g.ei[1] / inp.kT)),
                    (3, curve(xvib2, yvib2), exp(g.ei[3] / inp.kT)),
                    (5, curve(xvib3, yvib3), exp(g.ei[5] / inp.kT))]
  let excitations = [(7, curve(xvib4, yvib4)), (8, curve(xvib5, yvib5)),
                     (9, curve(xexc1, yexc1)), (10, curve(xexc2, yexc2)),
                     (11, curve(xexc3, yexc3))]

  for i, en in inp.steps:
    g.q[2, i] = if en <= xen[1]: float64(yxsec[1]) * 1e-16
                else: logLog(xen, yxsec, en) * 1e-16
    g.q[3, i] = if en < g.e[3]: 0.0 else: lin(xion, yion, en) * 1e-16
    g.q[4, i] = 0.0
    if en >= xatt[0] and en <= xatt[^1]: g.q[4, i] = lin(xatt, yatt, en) * 1e-21
    g.qatt[1, i] = g.q[4, i]
    g.q[5, i] = 0.0
    g.q[6, i] = 0.0
    for (j, c, apop) in vibrations:
      let e2 = en + g.ei[j + 1]
      g.qin[j, i] = e2 * lin(c, e2) / en
      g.qin[j, i] = g.qin[j, i] * apop / (1.0 + apop) * 1e-16
      g.qin[j + 1, i] = 0.0
      if en > g.ei[j + 1]: g.qin[j + 1, i] = lin(c, en) / (1.0 + apop) * 1e-16
    for (j, c) in excitations:
      g.qin[j, i] = 0.0
      if en > g.ei[j]: g.qin[j, i] = lin(c, en) * 1e-16
    var q = g.q[2, i] + g.q[3, i] + g.q[4, i]
    for j in 1 .. 11: q = q + g.qin[j, i]
    g.q[1, i] = q
  g.dropLevelsAbove(inp.efinal, first = 6)
