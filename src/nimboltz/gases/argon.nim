func phaseShifts(en: float64): tuple[qela, qmom: float64] =
  ## elastic and momentum transfer cross sections below 1 eV from the
  ## modified effective range theory (partial waves up to l = 99)
  const lmax = 100
  let apol = float64(11.08'f32)                # polarisability (a₀³)
  let (aa, dd, ff, a1) = (float64(-1.459'f32), float64(68.93'f32),
                          float64(-97.0'f32), float64(8.69'f32))
  let api = arccos(-1.0)
  let ak = sqrt(en / ary)
  let ak2 = ak * ak
  let ak3 = ak2 * ak
  let ak4 = ak3 * ak
  let an0 = arctan(-(aa * ak * (1.0 + 4.0 * apol / 3.0 * ak2 * ln(ak))) -
                   api * apol / 3.0 * ak2 + dd * ak3 + ff * ak4)
  let an1 = arctan(api / 15.0 * apol * ak2 - a1 * ak3)
  let an2 = arctan(api * apol * ak2 / 105.0)
  var anhigh = an2
  var sum = pow2(sin(an0 - an1)) + 2.0 * pow2(sin(an1 - an2))
  var sigel = pow2(sin(an0)) + 3.0 * pow2(sin(an1))
  for j in 2 .. lmax - 1:
    # (single precision, as written)
    let l = float32(j)
    let anlow = anhigh
    let d = (2.0'f32 * l + 5.0'f32) * (2.0'f32 * l + 3.0'f32) * (2.0'f32 * l + 1.0'f32)
    let sumi = float64(6.0'f32 / (d * (2.0'f32 * l - 1.0'f32)))
    sum = sum + float64(l + 1.0'f32) * pow2(sin(arctan(api * apol * ak2 * sumi)))
    anhigh = arctan(api * apol * ak2 / float64(d))
    sigel = sigel + float64(2.0'f32 * l + 1.0'f32) * pow2(sin(anlow))
  (sigel * 4.0 * pir2 / ak2, sum * 4.0 * pir2 / ak2)

