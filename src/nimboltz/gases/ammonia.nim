func topStates(): seq[RotState] =
  ## the symmetric top's states (J, K), J = 0 .. 14, K = 0 .. J: energies
  ## B J (J + 1) + (A - B) K² (A, B in units of 2 Ry, single precision in
  ## Magboltz), weight 2 for K a multiple of 3
  const ry = 13.605691909790039
  let ar = 2.8700000257231295e-05 * 2.0 * ry
  let br = 4.529999932856299e-05 * 2.0 * ry
  result.add (0.0, 0.0, 2.0)
  for j in 1 .. 14:
    for k in 0 .. j:
      let (aj, ak) = (float64(j), float64(k))
      result.add (br * aj * (aj + 1.0) + (ar - br) * ak * ak, aj, if k mod 3 == 0: 2.0 else: 1.0)

func topLoss(j: int): float64 =
  ## E(J, 0) - E(J - 1, 0)
  const states = topStates()
  states[j * (j + 1) div 2].e - states[(j - 1) * j div 2].e

