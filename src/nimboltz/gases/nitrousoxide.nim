      for l in 62 .. 120:
        if en <= g.ei[l]: continue
        let al = float64(l - 61)
        let s = sqrt(en - g.ei[l])
        g.qin[l, i] = pj[l - 61] * dbk * ln((enrt + s) / (enrt - s)) * (al + 1.0) /
                      ((2.0 * al + 1.0) * en)
        if en > 500.0: g.qin[l, i] = 0.0
      if en <= 500.0:
        for l in 61 .. 120: g.peqin[l, i] = 1.0 - lin(enrot, yepsr, en / abs(g.ei[l]))

    # (010), (100): Born dipole plus resonances, superelastic weighted by the
    # population of the excited state
    for (j, amp, ah, ar, apop, deg) in dipoleModes:
      let e2 = en + g.ei[j + 1]
      var q = vibrationalDipole(amp, g.ei[j], en)
      q = q + (if e2 > xvibh[^1] or e2 < xvibh[0]: 0.0
               else: ah * e2 * lin(xvibh, yvibh, e2) / en)
      q = q + (if e2 > xvibr[^1] or e2 < xvibr[0]: 0.0
               else: ar * e2 * lin(xvibr, yvibr, e2) / en)
      g.qin[j, i] = q * apop / deg * 1e-16
      if en > g.ei[j + 1]:
        q = vibrationalDipole(amp, g.ei[j + 1], en)
        q = q + (if en > xvibh[^1] or en < xvibh[0]: 0.0 else: ah * lin(xvibh, yvibh, en))
        q = q + (if en > xvibr[^1] or en < xvibr[0]: 0.0 else: ar * lin(xvibr, yvibr, en))
        g.qin[j + 1, i] = q * 1.0 * 1e-16
    # (020) from its table, superelastic by detailed balance
    block:
      let e2 = en + g.ei[124]
      g.qin[123, i] = if e2 > xv020[^1]: float64(yv020[^1]) * xv020[^1] / e2 * apop2v2 / 3.0 * 1e-16
                      else: e2 * lin(xv020, yv020, e2) / en * apop2v2 / 3.0 * 1e-16
      g.qin[124, i] = if en > xv020[^1]: float64(yv020[^1]) * xv020[^1] / en * 1.0 * 1e-16
                      elif en < xv020[0]: 0.0
                      else: lin(xv020, yv020, en) * 1.0 * 1e-16
    # (001)
    if en > g.ei[128]:
      var q = vibrationalDipole(0.29304'f32, g.ei[128], en)
      q = q + (if en > xvibh[^1] or en < xvibh[0]: 0.0 else: 0.4'f32 * lin(xvibh, yvibh, en))
      q = q + (if en > xvibr[^1] or en < xvibr[0]: 0.0 else: 0.20'f32 * lin(xvibr, yvibr, en))
      g.qin[128, i] = q * 1e-16
    for (j, c) in tables:
      g.qin[j, i] = if en > c.x[^1]: c.y[^1] * c.x[^1] / en * 1e-16
                    elif en < c.x[0]: 0.0
                    else: lin(c, en) * 1e-16
    g.qin[138, i] = if en > xvibh[^1]: float64(yvibh[^1]) * xvibh[^1] / en * 1e-16 * 2.8'f32
                    elif en < xvibh[0]: 0.0
                    else: lin(xvibh, yvibh, en) * 1e-16 * 2.8'f32
    if en >= 6.0:
      for j in 121 .. 138: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]

    for (j, c) in triplets:
      if en <= g.ei[j]: continue
      g.qin[j, i] = if en > c.x[^1]: c.y[^1] * pow(c.x[^1] / en, 1.5) * 1e-16
                    else: logLog(c.x, c.y, en) * 1e-16
      # (level 156 uses the threshold of level 147 in Magboltz)
      if en > 2.0 * g.ei[if j == 156: 147 else: j]:
        g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
    for j in 140 .. 179:
      let f = strengths[j]
      if f == 0.0 or en <= g.ei[j]: continue
      g.qin[j, i] = nonNegative(dipole(f, g.ei[j], r, en) / (en + g.e[3] + g.ei[j]))
      let epoint = en / abs(g.ei[j])
      g.peqin[j, i] = if epoint > 500.0: g.peqel[2, i - ioffn[j - 1]]
                      else: 1.0 - lin(enrot, yepsr, epoint)
  g.dropLevelsAbove(inp.efinal)
  if g.nin <= 120: g.nin = 120
