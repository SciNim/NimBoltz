proc mercuryDimer*(inp: GasInput, g: var GasXsec) =
  g.describe(inp, "MERCURY DIMER03", "MERCURY DIMER03", mass = 200.59)
  for k in 1 .. 6: g.kel[k] = 0
  g.scrp[2] = " ELASTIC (ISOT)  MERCURY"
  g.e[3] = 10.4375'f32
  g.shells [(0.0'f32, 10.4375'f32, 0, 0.0'f32, " IONISATION    ELOSS= 10.4375")]
  g.attachment [""]
  g.levels(inp, [
    (-0.040'f32, " DIMER SUPER   ELOSS= -0.040"),
    (0.040, " DIMER         ELOSS=  0.040"),
    (4.667, " EXC 3P0       ELOSS=  4.667"),
    (4.887, " EXC 3P1       ELOSS=  4.887"),
    (5.461, " EXC 3P2       ELOSS=  5.461"),
    (6.704, " EXC 1P1       ELOSS=  6.704"),
    (7.926, " EXC 1S0       ELOSS=  7.926"),
    (8.60, " EXC HIGH      ELOSS=  8.60")])
  for j in 1 .. g.nin: g.kin[j] = 0

  # dimer density relative to the 573 K, 760 Torr pure mercury of the table
  let gfrac = inp.percent(54) / 100.0
  let eande = float64(0.00221'f32)
  var dnorm = gfrac * (float64(573.0'f32) / (float64(273.15'f32) + inp.tempc)) *
              inp.torr / 760.0
  dnorm = dnorm * eande
  let apop = exp(g.ei[1] / inp.kT)
  let levels = [(3, curve(xexc3, yexc3)), (4, curve(xexc4, yexc4)),
                (5, curve(xexc5, yexc5)), (6, curve(xexc6, yexc6)),
                (7, curve(xexc7, yexc7)), (8, curve(xexc8, yexc8))]
  for i, en in inp.steps:
    # (the total elastic cross section, XEL/YEL, is not used)
    let qmom = if en <= float64(xen[1]): float64(yxsec[0]) * 1e-16
               else: logLog(xen, yxsec, en) * 1e-16
    g.peqel[2, i] = 0.0
    g.q[2, i] = qmom
    g.q[3, i] = if en <= g.e[3]: 0.0 else: lin(xion, yion, en) * 1e-16
    g.q[4, i] = 0.0
    g.qatt[1, i] = g.q[4, i]
    g.q[5, i] = 0.0
    g.q[6, i] = 0.0
    g.qin[1, i] = 0.0
    if en > 0.0:
      let eup = en + g.ei[2]
      g.qin[1, i] = eup * lin(xdim, ydim, eup) * 1e-16 / en
      g.qin[1, i] = g.qin[1, i] * apop / (1.0 + apop)
      g.qin[1, i] = g.qin[1, i] * dnorm
    g.qin[2, i] = 0.0
    if en > g.ei[2]:
      g.qin[2, i] = lin(xdim, ydim, en) * 1e-16
      g.qin[2, i] = g.qin[2, i] / (1.0 + apop)
      g.qin[2, i] = g.qin[2, i] * dnorm
    for (j, c) in levels:
      g.qin[j, i] = 0.0
      if en > g.ei[j]: g.qin[j, i] = lin(c, en) * 1e-16
    var q = g.q[2, i] + g.q[3, i]
    for j in 1 .. 8: q = q + g.qin[j, i]
    g.q[1, i] = q
  # levels from the first one strictly above the end of the grid are not used
  for k in 2 .. g.nin:
    if inp.efinal < g.ei[k]:
      g.nin = k - 1
      break
