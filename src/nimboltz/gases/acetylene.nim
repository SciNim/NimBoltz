proc acetylene*(inp: GasInput, g: var GasXsec) =
  g.describe(inp, " ACETYLENE 2002", " ACETYLENE 2002", mass = 26.03788)
  for k in 1 .. 6: g.kel[k] = 0
  g.scrp[2] = " ELASTIC       ACETYLENE"
  g.e[3] = 11.42'f32
  g.shells [(0.0'f32, 10.0'f32, 0, 0.0'f32, " IONISATION    ELOSS= 11.42")]
  g.attachment [" ATTACHMENT"]
  g.levels(inp, [
    (-0.0904'f32, " VIB V5        ELOSS= -0.0904"),
    (0.0904, " VIB V5        ELOSS=  0.0904"),
    (0.180, " VIB 2V5       ELOSS=  0.180"),
    (0.408, " VIB V3        ELOSS=  0.408"),
    (1.95, " EXC           ELOSS=  1.95"),
    (4.90, " EXC           ELOSS=  4.90"),
    (7.90, " EXC           ELOSS=  7.90")])
  for j in 1 .. g.nin: g.kin[j] = 0

  let apop = exp(g.ei[1] / inp.kT)
  let excitations = [(3, curve(xvib2, yvib2)), (4, curve(xvib3, yvib3)),
                     (5, curve(xexc1, yexc1)), (6, curve(xexc2, yexc2)),
                     (7, curve(xexc3, yexc3))]

  for i, en in inp.steps:
    g.q[2, i] = lin(xen, yxsec, en) * 1e-16
    g.q[3, i] = if en < g.e[3]: 0.0 else: lin(xion, yion, en) * 1e-16
    g.q[4, i] = 0.0
    if en >= xatt[0] and en <= xatt[^1]: g.q[4, i] = lin(xatt, yatt, en) * 1e-21
    g.qatt[1, i] = g.q[4, i]
    g.q[5, i] = 0.0
    g.q[6, i] = 0.0
    g.qin[1, i] = 0.0
    if en > 0.0:
      let e2 = en + g.ei[2]
      g.qin[1, i] = e2 * lin(xvib1, yvib1, e2) * 1e-16 / en
      g.qin[1, i] = 0.5 * g.qin[1, i] * apop / (1.0 + apop)
    g.qin[2, i] = 0.0
    if en > g.ei[2]: g.qin[2, i] = lin(xvib1, yvib1, en) * 1e-16 / (1.0 + apop)
    for (j, c) in excitations:
      g.qin[j, i] = 0.0
      if en > g.ei[j]: g.qin[j, i] = lin(c, en) * 1e-16
    var q = g.q[2, i] + g.q[3, i] + g.q[4, i]
    for j in 1 .. 7: q = q + g.qin[j, i]
    g.q[1, i] = q
  # Magboltz keeps the last level when the grid ends exactly at it
  # (EFINAL.LT.EIN(7), the others .LE.)
  if inp.efinal != g.ei[7]: g.dropLevelsAbove(inp.efinal)
