                           ((2.0 * aj + 1.0) * (2.0 * aj - 1.0))
      if en > g.ei[84]:
        g.qin[84, i] = frot0 * qbk * sqrt(1.0 - g.ei[84] / en) * 2.0 / 3.0
        for k in 29 .. 54:
          let aj = float64(k - 28)
          if en <= g.ei[k + 56]: continue
          g.qin[k + 56, i] = pj[k - 28] * qbk * sqrt(1.0 - g.ei[k + 56] / en) * (aj + 2.0) *
                             (aj + 1.0) / ((2.0 * aj + 3.0) * (2.0 * aj + 1.0))
      if en > 2.0:
        for j in 57 .. 110: g.qin[j, i] = 0.0

    # vibrations, isotropic below 4 eV
    let e2 = en + g.ei[112]
    if e2 <= xvib1[^1]:
      g.qin[111, i] = e2 * logLog(xvib1, yvib1, e2) / en
      g.qin[111, i] = g.qin[111, i] * apop * 1e-16
      if en >= 4.0: g.peqin[111, i] = g.peqel[2, i - ioffn[111]]
    if en > g.ei[112]:
      g.qin[112, i] = if en > xvib1[^1]: float64(yvib1[^1]) * pow2(float64(xvib1[^1]) / en) * 1e-16 * apopgs
                      else: logLog(xvib1, yvib1, en) * 1e-16 * apopgs
      if en >= 4.0: g.peqin[112, i] = g.peqel[2, i - ioffn[111]]
    for k, c in vibrations:
      let j = k + 113
      if en <= g.ei[j] or en > c.x[^1]: continue
      g.qin[j, i] = logLog(c, en) * 1e-16
      # (level 115 has the test inverted in Magboltz)
      if (j == 115) == (en <= 4.0): g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]

    # a3Π (123..128): none above 1 keV; level 128 stays isotropic
    block aPi:
      if en > 1000.0: break aPi
      for k, c in aTriplets:
        let j = k + 123
        if en <= g.ei[j]: break aPi
        g.qin[j, i] = table(c, en)
        if j != 128: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
    for (j, c) in triplets:
      if en <= g.ei[j]: continue
      g.qin[j, i] = table(c, en)
      g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]
    for (j, f) in dipoles:
      # (level 199 starts at the energy of level 194 in Magboltz)
      if en <= g.ei[if j == 199: 194 else: j]: continue
      g.qin[j, i] = nonNegative(dipole(f, g.ei[j], r, en, bbco) / (en + g.e[3] + g.ei[j]))
      if en > 2.0 * g.ei[j]: g.peqin[j, i] = g.peqel[2, i - ioffn[j - 1]]

    var sumrot, sumvib, sumexc = 0.0
    for k in 1 .. 110: sumrot = sumrot + g.qin[k, i]
    for k in 111 .. 122: sumvib = sumvib + g.qin[k, i]
    for k in 123 .. 204: sumexc = sumexc + g.qin[k, i]
    g.q[1, i] = g.q[2, i] + sumi + g.q[4, i] + sumexc + sumvib + sumrot
  g.dropLevelsAbove(inp.efinal)
  if g.nin < 113: g.nin = 113
