proc ozone*(inp: GasInput, g: var GasXsec) =
  g.describe(inp, " OZONE  2002", " OZONE  2002", mass = 47.9982)
  for k in 1 .. 6: g.kel[k] = 0
  g.scrp[2] = " ELASTIC        OZONE"
  g.e[3] = 12.75'f32
  g.shells [(0.0'f32, 12.75'f32, 0, 0.0'f32, " IONISATION    ELOSS= 12.75")]
  g.attachment [" DISOCIATIVE ATTACHMENT  O -",
                " DISOCIATIVE ATTACHMENT  O2 -"]
  g.levels(inp, [
    (-0.005'f32, " ROT           ELOSS= -0.005"),
    (0.005, " ROT           ELOSS=  0.005"),
    (-0.0869, " VIB2  BEND    ELOSS= -0.0869"),
    (0.0869, " VIB2 BEND     ELOSS=  0.0869"),
    (0.1292, " VIB3+VIB1     ELOSS=  0.1292"),
    (0.2161, " V12+V23       ELOSS=  0.2161"),
    (0.2660, " V13+2V1+2V3   ELOSS=  0.2660"),
    (0.380, " SUM HIGH VIB  ELOSS=  0.380"),
    (1.50, " EXC CHAPPUIS  ELOSS=  1.50"),
    (4.85, " EXC HARTLEY   ELOSS=  4.85"),
    (9.00, " EXC           ELOSS=  9.00")])
  for j in 1 .. g.nin: g.kin[j] = 0

  # dipole constants: rotation, V2, V3+V1
  let amp = [float64(0.450'f32), float64(0.0133'f32), float64(0.090'f32)]
  let apop = [exp(g.ei[1] / inp.kT), exp(g.ei[3] / inp.kT)]
  let levels = [(6, curve(xvib3, yvib3)), (7, curve(xvib4, yvib4)),
                (8, curve(xvib5, yvib5)), (9, curve(xexc1, yexc1)),
                (10, curve(xexc2, yexc2)), (11, curve(xexc3, yexc3))]
  for i, en in inp.steps:
    g.q[2, i] = if en == 0.0: 3000e-16 else: logLog(xen, yxsec, en) * 1e-16
    g.q[3, i] = if en < g.e[3]: 0.0 else: lin(xion, yion, en) * 1e-16
    g.qatt[1, i] = 0.0
    g.qatt[2, i] = 0.0
    if en >= float64(xatt[0]) and en <= float64(xatt[^1]):
      g.qatt[1, i] = lin(xatt, yat1, en) * 1e-16
      g.qatt[2, i] = lin(xatt, yat2, en) * 1e-16
    # (the attachment is not in Q(4) nor in the total)
    g.q[4, i] = 0.0
    g.q[5, i] = 0.0
    g.q[6, i] = 0.0
    g.qin[1, i] = 0.0
    if en != 0.0:
      g.qin[1, i] = vibrationalDipole(amp[0], g.ei[1], en)
      g.qin[1, i] = g.qin[1, i] * apop[0] / (1.0 + apop[0]) * 1e-16
    g.qin[2, i] = 0.0
    if en > g.ei[2]:
      g.qin[2, i] = vibrationalDipole(amp[0], g.ei[2], en)
      g.qin[2, i] = g.qin[2, i] * 1.0 / (1.0 + apop[0]) * 1e-16
    g.qin[3, i] = 0.0
    if en != 0.0:
      g.qin[3, i] = vibrationalDipole(amp[1], g.ei[3], en)
      g.qin[3, i] = g.qin[3, i] * apop[1] / (1.0 + apop[1]) * 1e-16
    g.qin[4, i] = 0.0
    if en > g.ei[4]:
      g.qin[4, i] = vibrationalDipole(amp[1], g.ei[4], en)
      g.qin[4, i] = lin(xvib1, yvib1, en) + g.qin[4, i]
      g.qin[4, i] = g.qin[4, i] * 1.0 / (1.0 + apop[1]) * 1e-16
    g.qin[5, i] = 0.0
    if en > g.ei[5]:
      g.qin[5, i] = vibrationalDipole(amp[2], g.ei[5], en)
      g.qin[5, i] = (lin(xvib2, yvib2, en) + g.qin[5, i]) * 1e-16
    for (j, c) in levels:
      g.qin[j, i] = 0.0
      if en > g.ei[j]: g.qin[j, i] = lin(c, en) * 1e-16
    var q = g.q[2, i] + g.q[3, i] + g.q[4, i]
    for j in 1 .. 11: q = q + g.qin[j, i]
    g.q[1, i] = q
  g.dropLevelsAbove(inp.efinal)
