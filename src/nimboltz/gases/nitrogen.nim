      let resfac = resonance(lin(xrot, yrot, en))
      if en <= g.ei[39]: break rotations
      g.qin[39, i] = frot0 * qbk * sqrt(1.0 - g.ei[39] / en) * 2.0 / 3.0
      g.qin[39, i] = g.qin[39, i] * resfac
      for k in 40 .. 76:
        let aj = float64(k - 39)
        if en <= g.ei[k]: break rotations
        g.qin[k, i] = pj[k - 39] * qbk * sqrt(1.0 - g.ei[k] / en) * (aj + 2.0) *
                      (aj + 1.0) / ((2.0 * aj + 3.0) * (2.0 * aj + 1.0))
        g.qin[k, i] = g.qin[k, i] * resfac
      if en < 5.0: break rotations
      let ascale = qmom / 8.90e-16
      for k in 1 .. 76: g.qin[k, i] = g.qin[k, i] * ascale

    # V1 de-excitation by detailed balance, excitation and harmonics
    let e2 = en - g.ei[77]
    g.qin[77, i] = if e2 > float64(xvb1[^1]):
                     e2 * float64(yvb1[^1]) * (float64(xvb1[^1]) / (en * en))
                   else: e2 * lin(xvb1, yvb1, e2) / en
    g.qin[77, i] = apopv1 * g.qin[77, i] * 1e-16
    g.qin[78, i] = if en > g.ei[78]: lin(xvb1, yvb1, en, 1.0) * 1e-16 else: 0.0
    for k, c in vibrations:
      g.qin[k + 79, i] = if en > g.ei[k + 79]: lin(c.x, c.y, en, 1.0) * 1e-16
                         else: 0.0
    for k in 1 .. 92:
      g.peqin[k, i] = if inp.naniso == 2: 0.0 else: 0.5
      if en > 3.0 * abs(g.ei[k]) and inp.naniso > 0:
        g.peqin[k, i] = g.peqel[2, i - ioffn[k - 1]]

    for k in 93 .. 121:
      let s = states[k]
      g.qin[k, i] = 0.0
      g.peqin[k, i] = if inp.naniso == 2: 0.0 else: 0.5
      if en <= g.ei[k]: continue
      var rat: float64
      if en > s.q.x[^1]:
        g.qin[k, i] = if s.f != 0.0: dipole(s.f, g.ei[k], r, en) / (en + g.ei[k] + g.e[3])
                      else: s.q.y[^1] * power(s.q.x[^1] / en, s.falloff) * 1e-16
        rat = s.m.y[^1] * (s.m.x[^1] / en)
      else:
        g.qin[k, i] = lin(s.q, en) * 1e-16
        rat = lin(s.q.x, s.m.y, en)
      if en <= 3.0 * g.ei[k]: continue
      if inp.naniso == 1: g.peqin[k, i] = 1.5 - rat
      if inp.naniso == 2: g.peqin[k, i] = g.peqel[2, i - ioffn[k - 1]]
    for (k, f) in singlets:
      g.qin[k, i] = 0.0
      g.peqin[k, i] = if inp.naniso == 2: 0.0 else: 0.5
      if en <= g.ei[k]: continue
      g.qin[k, i] = nonNegative(dipole(f, g.ei[k], r, en) / (en + g.ei[k] + g.e[3]))
      g.peqin[k, i] = g.peqin[121, i]
    # neutral dissociation above the ionisation energy
    for (k, f) in [(126, 0.1600'f32), (127, 0.0900)]:
      g.qin[k, i] = 0.0
      g.peqin[k, i] = if inp.naniso == 2: 0.0 else: 0.5
      if en <= g.e[3]: continue
      g.qin[k, i] = nonNegative(dipole(f, g.ei[k], r, en + 2.0 * g.ei[k]) / en)
      g.peqin[k, i] = g.peqin[121, i]

    # the rotations are part of the elastic cross section
    var sumr = 0.0
    for k in 1 .. 76: sumr = sumr + g.qin[k, i]
    g.q[2, i] = g.q[2, i] - sumr
    if g.q[2, i] <= 0.0: g.q[2, i] = 0.95e-16
  g.dropLevelsAbove(inp.efinal)
  if g.nin < 77: g.nin = 77
